import { IPC_CHANNELS, type OstlerAPI } from './ipc-types'
import type { Result } from './common-types'

/**
 * Every `OstlerAPI` call that is a plain request to main, and the IPC channel it
 * goes over. This is the one place a call is paired with its channel: the
 * preload builds its pass-throughs from it (`electron/preload.ts`) and main
 * registers handlers by method name (`handleApi`, `electron/ipc/handle-ipc.ts`),
 * typed from `OstlerAPI`.
 *
 * Not here, and hand-written in the preload: the `onX(callback)` subscriptions
 * and the `initial*` values.
 */
export type ApiInvokeMethod = Exclude<
  keyof OstlerAPI,
  `on${string}` | 'initialAppearance' | 'initialLocale'
>

/** The arguments the renderer passes to an `OstlerAPI` call. */
export type ApiArgs<M extends ApiInvokeMethod> = Parameters<OstlerAPI[M]>

/** A project-scoped call's arguments after the project id. */
export type ApiProjectArgs<M extends ApiInvokeMethod> =
  ApiArgs<M> extends [string, ...infer Rest] ? Rest : never

/** What an `OstlerAPI` call's handler returns (the `T` of its `Result<T>`). */
export type ApiValue<M extends ApiInvokeMethod> =
  Awaited<ReturnType<OstlerAPI[M]>> extends Result<infer T> ? T : never

