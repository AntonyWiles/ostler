/*
 * Keeps things that don't belong out of the repository: personal data (the
 * committer's own email, home-folder paths, personal mailboxes), secrets,
 * logs, build output, local databases, scratch and editor leftovers, and
 * large binaries. Also fails when such files sit untracked in the working
 * tree without being covered by .gitignore, so they can't be committed by a
 * stray `git add -A`.
 *
 *   node scripts/check-hygiene.cjs           every tracked file + untracked, not-ignored files
 *   node scripts/check-hygiene.cjs --staged  only what is staged (the pre-commit hook)
 *   node scripts/check-hygiene.cjs --push    every file in the commits being pushed (the
 *                                            pre-push hook; reads git's ref lines on stdin)
 *
 * Personal identifiers come from the machine running the check (git
 * user.email, the OS user name and home folder), so none are written here.
 * A line that legitimately needs a flagged value can carry `hygiene-allow`.
 *
 * Bucket credentials, plain or base64-encoded, and the exact values in this
 * clone's own secret files are refused too (scripts/lib/credential-scan.cjs).
 */
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { credentialReason, localSecrets, scanBuffer } = require('./lib/credential-scan.cjs')

const MAX_BYTES = 1024 * 1024

/** Paths that never belong in the repository, with the reason shown. */
const FORBIDDEN_PATHS = [
  [/(^|\/)node_modules\//, 'dependencies'],
  [/^(out|dist|release|coverage|test-results|\.vite|\.playwright)\//, 'build or test output'],
  [/^mobile\/(android|ios|\.expo)\//, 'generated mobile project'],
  [/\.tsbuildinfo$/, 'build output'],
  [/(^|\/)logs?\//, 'log folder'],
  [/\.(log|log\.\d+)$/i, 'log file'],
  [/\.(db|db-wal|db-shm|db-journal|sqlite|sqlite3)$/i, 'local database'],
  [/(^|\/)\.env(\.(?!example$)[^/]+)?$/, 'environment file'],
  [/\.(pem|key|p12|pfx|keystore|jks)$/i, 'key or certificate'],
  [/(^|\/)secrets\//i, 'secrets folder'],
  [/\.(tmp|temp|bak|orig|rej|swp|swo)$|~$/i, 'scratch or editor leftover'],
  [/(^|\/)(\.DS_Store|Thumbs\.db|desktop\.ini)$/i, 'OS file'],
  [/\.(zip|7z|rar|tar|gz|tgz|exe|msi|dmg|appimage|deb|rpm|apk|aab|asar)$/i, 'archive or binary'],
  [/(^|\/)(scratch|tmp|temp)\//i, 'scratch folder'],
  [/(^|\/)(npm-debug|yarn-error|yarn-debug)/, 'package-manager log'],
  [/^\.claude\/(settings(\.local)?\.json|handoff\.md)$/, 'personal agent settings'],
  [/(^|\/)(handoff|scratch|notes|todo)\.(md|txt)$/i, 'agent working note'],
  [/(^|\/)[^/]*(dump|-debug)\.(txt|json)$/i, 'debug dump']
]

/** Content that never belongs in the repository. */
const SECRET_PATTERNS = [
  [/-----BEGIN [A-Z ]*PRIVATE KEY-----/, 'private key'],
  [/\bgh[pousr]_[A-Za-z0-9]{30,}\b|\bgithub_pat_[A-Za-z0-9_]{40,}/, 'GitHub token'],
  [/\bsk-ant-[A-Za-z0-9_-]{20,}/, 'Anthropic API key'],
  [/\bsk-(proj-)?[A-Za-z0-9]{32,}\b/, 'OpenAI-style API key'],
  [/\bAKIA[0-9A-Z]{16}\b/, 'AWS access key'],
  [/\bxox[abposr]-[A-Za-z0-9-]{10,}/, 'Slack token'],
  [/\bAIza[0-9A-Za-z_-]{35}\b/, 'Google API key']
]

const PERSONAL_MAILBOX =
  /\b[A-Za-z0-9._%+-]+@(gmail|googlemail|outlook|hotmail|live|msn|yahoo|icloud|me|mac|proton|protonmail|aol|gmx)\.[a-z.]{2,6}\b/i

/** Files whose content is generated by tools and not ours to police. */
const CONTENT_SKIP = /(^|\/)(package-lock\.json|THIRD_PARTY[^/]*)$/

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/**
 * Patterns for this machine's personal identifiers: the git email (unless it
 * is a GitHub noreply address), and home-folder paths that name the OS user.
 */
function personalPatterns({ email, userName, homeDir }) {
  const patterns = []
  if (email && !/noreply/i.test(email)) {
    patterns.push([new RegExp(escapeRegExp(email), 'i'), "committer's own email"])
  }
  if (userName && userName.length >= 3) {
    const user = escapeRegExp(userName)
    patterns.push([
      new RegExp(`[A-Za-z]:[\\\\/]+Users[\\\\/]+${user}\\b|/(Users|home)/${user}\\b`, 'i'),
      'path to your home folder'
    ])
  }
  if (homeDir) {
    // The working folder that holds this repository is private too.
    const parent = path.dirname(path.resolve(__dirname, '..', '..'))
    if (parent !== path.dirname(parent) && parent.toLowerCase() !== homeDir.toLowerCase()) {
      const variants = new Set([parent, parent.replace(/\\/g, '/'), parent.replace(/\\/g, '\\\\')])
      const alternatives = [...variants].map(escapeRegExp).join('|')
      patterns.push([new RegExp(`(${alternatives})([\\\\/]|$)`, 'i'), 'local working-folder path'])
    }
  }
  return patterns
}

/** Returns the reason a path may not be committed, or null. */
function forbiddenPathReason(file) {
  const normal = file.replace(/\\/g, '/')
  const hit = FORBIDDEN_PATHS.find(([pattern]) => pattern.test(normal))
  return hit ? hit[1] : null
}

/** Returns one message per problem line in `text`. */
function contentProblems(file, text, personal) {
  if (CONTENT_SKIP.test(file.replace(/\\/g, '/'))) return []
  const problems = []
  const lines = text.split(/\r?\n/)
  lines.forEach((line, index) => {
    if (line.includes('hygiene-allow')) return
    const credential = credentialReason(line)
    if (credential) {
      problems.push(`${file}:${index + 1}: ${credential}`)
      return
    }
    const rules = [...SECRET_PATTERNS, ...personal, [PERSONAL_MAILBOX, 'personal email address']]
    for (const [pattern, reason] of rules) {
      if (pattern.test(line)) {
        problems.push(`${file}:${index + 1}: ${reason}`)
        break
      }
    }
  })
  return problems
}

function git(root, args) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
}

const list = (output) => output.split('\0').filter(Boolean)

/** `rev` is undefined for the working tree, '' for the index, or a commit. */
function readTarget(root, file, rev) {
  if (rev !== undefined) {
    return execFileSync('git', ['show', `${rev}:${file}`], {
      cwd: root,
      maxBuffer: 64 * 1024 * 1024
    })
  }
  return fs.readFileSync(path.join(root, file))
}

const ZERO = /^0+$/

/** [commit, file] for every file added or changed by the commits a push sends. */
function pushedFiles(root, refLines) {
  const targets = []
  for (const line of refLines.split(/\r?\n/).filter(Boolean)) {
    const [, localSha, , remoteSha] = line.split(' ')
    if (!localSha || ZERO.test(localSha)) continue // deleting a remote branch
    const range = ZERO.test(remoteSha)
      ? [localSha, '--not', '--remotes']
      : [`${remoteSha}..${localSha}`]
    for (const commit of git(root, ['rev-list', ...range])
      .split(/\s+/)
      .filter(Boolean)) {
      const changed = git(root, [
        'diff-tree',
        '-r',
        '--root',
        '--no-commit-id',
        '--name-only',
        '--diff-filter=ACMR',
        '-z',
        commit
      ])
      for (const file of list(changed)) targets.push([commit, file])
    }
  }
  return targets
}

function isBinary(buffer) {
  return buffer.subarray(0, 8000).includes(0)
}

function main(root, { staged, push }) {
  const problems = []
  const personal = personalPatterns({
    email: (() => {
      try {
        return git(root, ['config', 'user.email']).trim()
      } catch {
        return ''
      }
    })(),
    userName: os.userInfo().username,
    homeDir: os.homedir()
  })

  const secrets = localSecrets(root)
  const targets = push
    ? pushedFiles(root, push)
    : (staged
        ? list(git(root, ['diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z']))
        : list(git(root, ['ls-files', '-z'])).filter((file) => fs.existsSync(path.join(root, file)))
      ).map((file) => [staged ? '' : undefined, file])

  for (const [rev, file] of targets) {
    const where = rev ? `${rev.slice(0, 8)}:${file}` : file
    const reason = forbiddenPathReason(file)
    if (reason) problems.push(`${where}: ${reason} must not be committed`)
    const buffer = readTarget(root, file, rev)
    for (const secret of scanBuffer(buffer, secrets).filter((hit) => hit.startsWith('secret '))) {
      problems.push(`${where}: ${secret}`)
    }
    if (buffer.length > MAX_BYTES && !/^build\//.test(file)) {
      problems.push(`${where}: ${(buffer.length / 1048576).toFixed(1)} MB, over the 1 MB limit`)
    }
    if (!isBinary(buffer))
      problems.push(...contentProblems(where, buffer.toString('utf8'), personal))
  }

  // Untracked files that git would pick up: junk must be ignored or removed.
  const untracked = push
    ? []
    : list(git(root, ['ls-files', '--others', '--exclude-standard', '-z']))
  for (const file of untracked) {
    const reason = forbiddenPathReason(file)
    if (reason) problems.push(`${file}: untracked ${reason}; delete it or add it to .gitignore`)
  }

  for (const problem of problems) process.stderr.write(`check-hygiene: ${problem}\n`)
  if (problems.length) {
    process.stderr.write(
      'check-hygiene: keep personal data, logs, build output and scratch files out of the repo.\n'
    )
  }
  return problems.length === 0 ? 0 : 1
}

if (require.main === module) {
  process.exitCode = main(require('./lib/root.cjs').projectRoot, {
    staged: process.argv.includes('--staged'),
    push: process.argv.includes('--push') ? fs.readFileSync(0, 'utf8') || ' ' : null
  })
}

module.exports = { forbiddenPathReason, contentProblems, personalPatterns }
